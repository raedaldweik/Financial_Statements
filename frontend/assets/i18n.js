/* translate the static markup: every text node, placeholder and title whose
   (whitespace-normalised) text is a dictionary key */
function i18nTree(root) {
  if (LANG !== 'ar' || !root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, { acceptNode: n => {
    const p = n.parentNode; if (!p || p.tagName === 'SCRIPT' || p.tagName === 'STYLE') return NodeFilter.FILTER_REJECT;
    return n.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_SKIP; } });
  const nodes = []; while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const n of nodes) {
    const raw = n.nodeValue, key = raw.trim().replace(/\s+/g, ' '), v = AR[key];
    if (v == null) continue;
    const p = n.parentNode;
    if (p.tagName === 'OPTION' && !p.hasAttribute('value')) p.setAttribute('value', key); // keep English values
    const m = raw.match(/^(\s*)[\s\S]*?(\s*)$/); n.nodeValue = m[1] + v + m[2];
  }
  root.querySelectorAll('[placeholder]').forEach(el => { const v = AR[el.getAttribute('placeholder')]; if (v) el.setAttribute('placeholder', v); });
  root.querySelectorAll('[title]').forEach(el => { const v = AR[el.getAttribute('title')]; if (v) el.setAttribute('title', v); });
}

function initLang() {
  if (LANG === 'ar') { document.title = t(document.title); i18nTree(document.body); }
  const host = document.querySelector('.nav-right');
  if (host && !host.querySelector('.lang-btn')) {
    const b = document.createElement('button');
    b.type = 'button'; b.className = 'lang-btn';
    b.textContent = LANG === 'ar' ? 'English' : 'العربية';
    b.title = LANG === 'ar' ? 'Switch to English' : 'التبديل إلى العربية';
    b.onclick = () => { try { localStorage.setItem('fcuLang', LANG === 'ar' ? 'en' : 'ar'); } catch (e) {} location.reload(); };
    host.appendChild(b);
  }
}
